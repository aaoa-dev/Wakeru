/* Builds data/wards/<id>.json (+ .dict.json) and data/wards.json from each ward's curated ruleset and its official sources.
   Usage: node scripts/import/index.mjs [ward ...] [--refresh]   (no ward = all) */
import fs from "node:fs";
import path from "node:path";
import { ROOT, readJSON, writeJSON, download, decode, csvObjects, townRegistry, buildAreas } from "./lib.mjs";
import { importDictionary } from "./dictionary.mjs";

const WARDS_DIR = path.join(ROOT, "scripts/import/wards");
const today = new Date().toISOString().slice(0, 10);
const all = fs.readdirSync(WARDS_DIR).filter(d => fs.existsSync(path.join(WARDS_DIR, d, "ruleset.json"))).sort();
const picked = process.argv.slice(2).filter(a => !a.startsWith("--"));
const ids = picked.length ? picked : all;

/* strip research-only fields (evidence, open questions) before shipping */
const RESEARCH_ONLY = key => key === "evidence" || key.endsWith("Evidence") || key === "holidays";
const stripResearch = v => Array.isArray(v) ? v.map(stripResearch)
  : v && typeof v === "object" ? Object.fromEntries(Object.entries(v).filter(([k]) => !RESEARCH_ONLY(k)).map(([k, x]) => [k, stripResearch(x)])) : v;
function shippedRuleset(rs){
  const sorting = Object.fromEntries(Object.entries(rs.sorting).map(([t, v]) => [t, v.note ? {bin:v.bin, note:v.note} : v.bin]));
  return stripResearch({id:rs.id, jp:rs.jp, en:rs.en, verified:rs.verified, sources:rs.sources, contacts:rs.contacts, bins:rs.bins, plasticTest:rs.plasticTest, sorting, calendar:rs.calendar});
}
function checkPatterns(rs, patterns){
  for(const [id, p] of Object.entries(patterns)) for(const bin of Object.keys(p))
    if(!rs.bins[bin]) throw new Error(`${rs.id}: pattern ${id} uses bin "${bin}" that the ruleset doesn't define`);
}

let failed = false;
for(const id of ids){
  try {
    const rs = readJSON(path.join(WARDS_DIR, id, "ruleset.json"));
    const mod = await import(path.join(WARDS_DIR, id, "import.mjs"));
    const towns = await townRegistry(rs.jp);
    for(const [jp, en] of Object.entries(rs.townNames ?? {})){
      if(!towns.has(jp)) throw new Error(`townNames: "${jp}" is not an official town`);
      towns.get(jp).en = en;
    }
    const raw = await mod.areas({rs, towns, download:url => download(id, url), decode, csvObjects, dir:path.join(WARDS_DIR, id)});
    const {patterns, areas, coverage} = buildAreas(raw.areas ?? raw, towns, {patternIds:mod.patternId});
    Object.assign(patterns, raw.patterns ?? {});
    checkPatterns(rs, patterns);
    const orphan = areas.find(a => !patterns[a.pattern]);
    if(orphan) throw new Error(`area ${orphan.town} ${orphan.jp} uses missing pattern "${orphan.pattern}"`);
    const ward = shippedRuleset(rs);
    ward.updated = today;
    ward.calendar = {...ward.calendar, ...(raw.validTo ? {validTo:raw.validTo} : {}), patterns};
    ward.areas = areas;
    const dict = rs.dictionary ? await importDictionary(rs, url => download(id, url)) : null;
    const out = rs.status === "verified" ? path.join(ROOT, "data/wards") : path.join(ROOT, ".cache/preview");
    writeJSON(path.join(out, `${id}.json`), ward);
    if(dict) writeJSON(path.join(out, `${id}.dict.json`), dict);
    console.log(`${id}: ${rs.status}, ${areas.length} areas, ${Object.keys(patterns).length} patterns${dict ? `, ${dict.items.length} dictionary items` : ""} → ${path.relative(ROOT, out)}`);
    if(coverage.length) console.log(`  not covered by any area (${coverage.length}): ${coverage.join(" ")}`);
  } catch(err) {
    failed = true;
    console.error(`${id}: FAILED: ${err.message}`);
  }
}

/* index of shipped wards */
const shipped = all.map(id => readJSON(path.join(WARDS_DIR, id, "ruleset.json"))).filter(rs => rs.status === "verified")
  .filter(rs => fs.existsSync(path.join(ROOT, "data/wards", `${rs.id}.json`)));
writeJSON(path.join(ROOT, "data/wards.json"), {
  _readme:"Wards shown in the app. Generated by scripts/import; a ward is listed only after its data has been checked against the ward's current official sources.",
  version:today,
  wards:shipped.map(rs => ({id:rs.id, en:rs.en, jp:rs.jp, verified:rs.verified, dictionary:!!rs.dictionary})),
});
process.exitCode = failed ? 1 : 0;
